/** Places whose name or region contains the query (spaces ignored), names that start with it first. */
export function searchKoreaPlaces(query: string, limit = 8): KoreaPlace[] {
  const q = query.replace(/\s+/g, '');
  if (!q) return [];
  const hits = KOREA_PLACES.filter(p => p.name.includes(q) || p.region.includes(q));
  hits.sort((a, b) => Number(!a.name.startsWith(q)) - Number(!b.name.startsWith(q)));
  return hits.slice(0, limit);
}

export const findKoreaPlace = (name?: string | null): KoreaPlace | undefined =>
  name ? KOREA_PLACES.find(p => p.name === name) : undefined;
