"""Turns the Blender renders (output/plates, from build_cheese_home.py) into the app's story assets.

python3 -I 3d-modeling/cheese/scripts/export_story_assets.py <plates_dir> <repo_root>

Writes src/features/story/assets/cheese/:
  <plate>.jpg            full plate, 1170x2080
  <plate>_<expr>.jpg     the face crop for each expression (same render, same camera)
  cheese_card.jpg        Home card art: Cheese on the sofa, cropped from the sofa plate
and generates src/features/story/data/plates.ts (requires + face rects) from the render manifest.
"""
import json
import os
import sys

from PIL import Image

plates_dir, repo = sys.argv[1], sys.argv[2]
out = os.path.join(repo, "src/features/story/assets/cheese")
os.makedirs(out, exist_ok=True)
man = json.load(open(os.path.join(plates_dir, "manifest.json")))
W, H = man["resolution"]

ts = [
    "// GENERATED by 3d-modeling/cheese/scripts/export_story_assets.py from the Blender render manifest —",
    "// do not edit by hand; re-run the script after re-rendering (build_cheese_home.py).",
    "import type { ImageSourcePropType } from 'react-native';",
    "import type { PlateId } from '../types';",
    "",
    "export type Expression = 'idle' | 'blink' | 'talk' | 'smug';",
    "",
    "export interface PlateArt {",
    "  image: ImageSourcePropType;",
    "  /** The cat's face: [x0, y0, x1, y1] as fractions of the plate (y from the top) and one crop per",
    "   *  expression, cut from the same render so it sits on the plate seamlessly. */",
    "  face?: { rect: [number, number, number, number]; variants: Partial<Record<Expression, ImageSourcePropType>> };",
    "}",
    "",
    f"export const PLATE_SIZE = {{ w: {W}, h: {H} }};",
    "",
    "export const PLATES: Record<PlateId, PlateArt> = {",
]
for name, entry in man["plates"].items():
    im = Image.open(os.path.join(plates_dir, entry["file"])).convert("RGB")
    im.save(os.path.join(out, f"{name}.jpg"), quality=84, optimize=True, progressive=True)
    line = f"  {name}: {{ image: require('../assets/cheese/{name}.jpg')"
    if "face" in entry:
        x0, y0, x1, y1 = entry["face"]
        # The crop Blender wrote is the pixel-snapped border: recompute the rect from its real size so
        # the overlay lands on exact pixels.
        # Blender truncates the border to whole pixels, and counts y from the bottom.
        px0 = int(x0 * W)
        ymin_bottom = int((1 - y1) * H)
        variants = []
        for expr, f in entry["variants"].items():
            crop = Image.open(os.path.join(plates_dir, f)).convert("RGB")
            cw, ch = crop.size
            crop.save(os.path.join(out, f"{name}_{expr}.jpg"), quality=90, optimize=True)
            variants.append(f"{expr}: require('../assets/cheese/{name}_{expr}.jpg')")
        py0 = H - ymin_bottom - ch
        # Verify against the plate: the idle crop must match it where it lands. Search a few pixels
        # around the computed spot and keep the best fit (and say how good it is).
        import numpy as np
        plate = np.asarray(im, dtype=np.float32)
        idle = np.asarray(Image.open(os.path.join(plates_dir, entry["variants"]["idle"])).convert("RGB"), dtype=np.float32)
        best = None
        for dy in range(-3, 4):
            for dx in range(-3, 4):
                x, y = px0 + dx, py0 + dy
                if x < 0 or y < 0 or x + cw > W or y + ch > H:
                    continue
                d = float(np.abs(plate[y:y + ch, x:x + cw] - idle).mean())
                if best is None or d < best[0]:
                    best = (d, x, y)
        print(f"{name}: face crop {cw}x{ch} at ({best[1]},{best[2]}) mean abs diff {best[0]:.2f} (offset {best[1]-px0},{best[2]-py0})")
        px0, py0 = best[1], best[2]
        rect = [px0 / W, py0 / H, (px0 + cw) / W, (py0 + ch) / H]
        line += f", face: {{ rect: [{', '.join(f'{v:.5f}' for v in rect)}], variants: {{ {', '.join(variants)} }} }}"
    ts.append(line + " },")
ts += ["};", ""]

# Home card: Cheese on the sofa, landscape crop around the face rect of the sofa plate.
sofa = Image.open(os.path.join(plates_dir, "sofa.png")).convert("RGB")
fx0, fy0, fx1, fy1 = man["plates"]["sofa"]["face"]
cx, cy = (fx0 + fx1) / 2 * W, (fy0 + fy1) / 2 * H
cw = W
ch = int(cw * 0.62)
top = int(min(max(0, cy - ch * 0.38), H - ch))
card = sofa.crop((0, top, cw, top + ch)).resize((1000, int(1000 * 0.62)), Image.LANCZOS)
card.save(os.path.join(out, "cheese_card.jpg"), quality=86, optimize=True, progressive=True)
ts += ["/** Home card art: Cheese on the sofa. */", "export const CHEESE_CARD: ImageSourcePropType = require('../assets/cheese/cheese_card.jpg');", ""]

open(os.path.join(repo, "src/features/story/data/plates.ts"), "w").write("\n".join(ts))
print("exported", sorted(os.listdir(out)))
